// The reconciler must replace ONLY the seeds value and leave every other key
// byte-identical — scylla.yaml is written by the package post-install and
// carries settings (cluster_name, listen_address, replace_address_first_boot)
// that this reconciler has no authority over.
func TestScyllaSeedsRewrite_ReplacesOnlySeedsValue(t *testing.T) {
	const original = `# Generated by Globular post-install — do not edit manually.
cluster_name: 'globular.internal'

listen_address: '10.10.0.11'
rpc_address: '10.10.0.11'

seed_provider:
  - class_name: org.apache.cassandra.locator.SimpleSeedProvider
    parameters:
      - seeds: '10.10.0.11'

endpoint_snitch: SimpleSnitch
developer_mode: true
`
	got, current, ok := rewriteScyllaSeedsForTest(t, original, "10.10.0.11,10.10.0.12,10.10.0.13")
	if !ok {
		t.Fatal("seeds line not matched")
	}
	if current != "10.10.0.11" {
		t.Errorf("current seeds = %q, want %q", current, "10.10.0.11")
	}
	if !strings.Contains(got, "      - seeds: '10.10.0.11,10.10.0.12,10.10.0.13'\n") {
		t.Errorf("rewritten seeds line missing or misindented:\n%s", got)
	}
	for _, must := range []string{
		"# Generated by Globular post-install — do not edit manually.\n",
		"cluster_name: 'globular.internal'\n",
		"listen_address: '10.10.0.11'\n",
		"rpc_address: '10.10.0.11'\n",
		"  - class_name: org.apache.cassandra.locator.SimpleSeedProvider\n",
		"endpoint_snitch: SimpleSnitch\n",
		"developer_mode: true\n",
	} {
		if !strings.Contains(got, must) {
			t.Errorf("reconciler disturbed an unrelated line, missing: %q", must)
		}
	}
	if strings.Count(got, "seeds:") != 1 {
		t.Errorf("expected exactly one seeds line, got %d", strings.Count(got, "seeds:"))
	}
}

// The founding-node case that produced the doctor ERROR: a self-only seed list
// on a node that is already a member of a multi-node ring.
func TestScyllaSeedsRewrite_FoundingNodeSelfOnlyConverges(t *testing.T) {
	original := "seed_provider:\n  - class_name: X\n    parameters:\n      - seeds: '10.10.0.11'\n"
	got, current, ok := rewriteScyllaSeedsForTest(t, original, "10.10.0.11,10.10.0.12,10.10.0.13")
	if !ok || current != "10.10.0.11" {
		t.Fatalf("match failed: ok=%v current=%q", ok, current)
	}
	if !strings.Contains(got, "- seeds: '10.10.0.11,10.10.0.12,10.10.0.13'") {
		t.Errorf("self-only seed list did not converge:\n%s", got)
	}
}

// An already-correct file must be recognised as such, so the reconciler makes
// no write and scylla.yaml's mtime stays stable across ticks.
func TestScyllaSeedsRewrite_AlreadyCorrectIsNoOp(t *testing.T) {
	original := "      - seeds: '10.10.0.11,10.10.0.12'\n"
	_, current, ok := rewriteScyllaSeedsForTest(t, original, "10.10.0.11,10.10.0.12")
	if !ok {
		t.Fatal("seeds line not matched")
	}
	if current != "10.10.0.11,10.10.0.12" {
		t.Fatalf("current = %q", current)
	}
}

// A file with no seed_provider section must be left alone rather than have a
// seeds line invented at an arbitrary position.
func TestScyllaSeedsRewrite_NoSeedsLineLeavesFileUntouched(t *testing.T) {
	if loc := scyllaSeedsLineRe.FindSubmatchIndex([]byte("cluster_name: 'x'\n")); loc != nil {
		t.Errorf("matched a seeds line in a file that has none: %v", loc)
	}
}

// Double quotes and tab indentation must parse too — the post-install script is
// not the only thing that has ever written this file.
func TestScyllaSeedsRewrite_HandlesDoubleQuotes(t *testing.T) {
	_, current, ok := rewriteScyllaSeedsForTest(t, "      - seeds: \"10.0.0.1,10.0.0.2\"\n", "10.0.0.1")
	if !ok {
		t.Fatal("double-quoted seeds line not matched")
	}
	if current != "10.0.0.1,10.0.0.2" {
		t.Errorf("current = %q, want %q", current, "10.0.0.1,10.0.0.2")
	}
}

// writeFileAtomic must leave no temp files behind and must land the content.
func TestWriteFileAtomic_LeavesNoTempAndLandsContent(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "scylla.yaml")
	if err := writeFileAtomic(path, []byte("hello\n"), 0o644); err != nil {
		t.Fatalf("writeFileAtomic: %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != "hello\n" {
		t.Errorf("content = %q", got)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 {
		var names []string
		for _, e := range entries {
			names = append(names, e.Name())
		}
		t.Errorf("expected only the target file, got %v", names)
	}
}

// rewriteScyllaSeedsForTest applies the same match-and-splice the reconciler
// uses, so the tests exercise the real regexp and offsets rather than a copy.
func rewriteScyllaSeedsForTest(t *testing.T, in, desired string) (out, current string, ok bool) {
	t.Helper()
	raw := []byte(in)
	loc := scyllaSeedsLineRe.FindSubmatchIndex(raw)
	if loc == nil {
		return "", "", false
	}
	prefixEnd := loc[3]
	current = strings.Trim(strings.TrimSpace(string(raw[prefixEnd:loc[1]])), `'"`)
	b := make([]byte, 0, len(raw)+len(desired))
	b = append(b, raw[:prefixEnd]...)
	b = append(b, '\'')
	b = append(b, desired...)
	b = append(b, '\'')
	b = append(b, raw[loc[1]:]...)
	return string(b), current, true
}
